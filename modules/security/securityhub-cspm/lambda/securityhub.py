"""Security Hub control-finding notification policy.

Security Hub's own control findings (ProductName "Security Hub") are re-imported
on every AWS Config re-evaluation, so a single unresolved control would otherwise
generate a notification every day. This policy throttles them to keep the inbox
signal high:

  - notify on the day the finding is first observed
  - send a monthly reminder on the 1st of each month
  - suppress on every other day

The discriminator is the finding's ``ProductName``, not the EventBridge event
``source``: every finding — GuardDuty, Inspector, Macie, IAM Access Analyzer, and
the control checks — is delivered as a single "Security Hub Findings - Imported"
event whose source is always ``aws.securityhub``. Only ``ProductName`` identifies
the product that actually generated the finding.

Findings from other products are not handled here; the handler notifies on them
unconditionally. To give another product its own rules later, add a sibling
module exposing the same ``matches``/``should_notify`` pair and register it in
``format_findings``.
"""

from datetime import datetime

# ASFF ProductName values that identify a native Security Hub control finding.
# "Security Hub" is the historical value; "Security Hub CSPM" covers the
# post-rename naming. Integrated services carry their own product name
# ("GuardDuty", "Inspector", ...) and therefore never match.
PRODUCT_NAMES = frozenset({"Security Hub", "Security Hub CSPM"})

# Notification framing types shared with the formatter. A falsy value means
# "notify with standard framing".
FIRST_OBSERVED = "first_observed"
MONTHLY_REMINDER = "monthly_reminder"


def matches(finding):
    """True if the finding was generated by Security Hub's own controls."""
    return (finding.get("ProductName") or "") in PRODUCT_NAMES


def _parse_iso_date(iso_str):
    """Parse an ISO 8601 timestamp to a datetime, or None if absent/invalid."""
    if not iso_str:
        return None
    try:
        return datetime.fromisoformat(iso_str.replace("Z", "+00:00"))
    except (ValueError, TypeError):
        return None


def should_notify(finding):
    """Decide whether a Security Hub control finding should be delivered.

    Returns a ``(should_notify, notification_type)`` tuple, where
    ``notification_type`` is one of ``FIRST_OBSERVED``, ``MONTHLY_REMINDER`` or
    ``None`` (standard framing).
    """
    first_observed = _parse_iso_date(
        finding.get("FirstObservedAt") or finding.get("CreatedAt")
    )
    updated_at = _parse_iso_date(finding.get("UpdatedAt"))

    # No usable first-observed timestamp: treat as new and notify.
    if first_observed is None:
        return True, None

    # No usable update timestamp: cannot evaluate the throttle, so notify.
    if updated_at is None:
        return True, None

    # First time we have seen this finding — always the first notification.
    if first_observed.date() == updated_at.date():
        return True, FIRST_OBSERVED

    # Monthly reminder for an unresolved finding, on the 1st of the month.
    if updated_at.day == 1:
        return True, MONTHLY_REMINDER

    return False, None
